const assert=require('node:assert/strict');
const fs=require('node:fs');
assert(fs.existsSync('replica/focus-core.js'),'A persistent focus clock core is required');
const F=require('../replica/focus-core.js');
const at=time=>Date.parse('2026-10-18T'+time+':00+08:00');
const plan={id:'p',kind:'event',title:'原计划',goalId:'a',taskBlock:true,date:'2026-10-18',time:'09:00',endDate:'2026-10-18',endTime:'10:00'};
assert.equal(F.available(plan,at('08:59')),false,'Scheduled focus is locked before start');
assert.equal(F.available(plan,at('09:00')),true,'Scheduled focus unlocks at exact start');
let session=F.start({id:'f',goalId:'a',plan},at('09:10'));
assert.equal(F.elapsed(session,at('09:20')),600000,'Running uses wall clock, not tick increments');
session=F.pause(session,at('09:20'));
assert.equal(F.elapsed(session,at('09:40')),600000,'Pause never adds invested time');
session=F.resume(session,at('09:40'));
session=F.reconcile(session,at('10:05'));
assert.equal(session.status,'boundary','Plan ends even if a timer callback was delayed');
assert.equal(F.elapsed(session,at('10:05')),1800000,'Boundary caps the scheduled segment');
session=F.extend(session,at('10:05'));
session=F.finish(session,at('10:10'));
assert.equal(F.elapsed(session,at('10:20')),2400000,'Confirmed continuation extends from the boundary');
const projected=F.project([plan,{id:'a',kind:'todo',title:'A'}],session);
assert.equal(projected.filter(x=>x.focusActual).length,3,'Pause produces separate actual intervals');
assert.equal(projected.find(x=>x.id==='p').endTime,'10:10','Planned target reflects actual extended end');
assert.equal(projected.find(x=>x.id==='p').planOriginal.endTime,'10:00','Original plan stays recoverable');
assert.equal(F.project(projected,session).length,projected.length,'Projection is idempotent');
assert.equal(F.snap(67),60,'Range editing snaps to quarter hours');
assert.equal(F.snap(69),75);
console.log('PASS focus gate, persistent clock, pause, boundary, continue, interval projection and snapping');
const Goal=require('../replica/planner.js');
const original={...plan,done:true};
let replacement=F.start({id:'replacement',goalId:'b',goalTitle:'B'},at('09:15'));
replacement=F.finish(replacement,at('09:45'));
const replacementItems=F.project([original,{id:'a',kind:'todo',date:'',title:'A'},{id:'b',kind:'todo',date:'',title:'B'}],replacement);
assert.equal(Goal.goalMinutes(replacementItems,'a',at('10:30')),30,'Actual B replaces the overlap, not adding a second planned credit');
assert.equal(Goal.goalMinutes(replacementItems,'b',at('10:30')),30);
const restored=Goal.mergeBackup({items:[],settings:{categories:[]}}, {version:3,items:replacementItems,focusSessions:[replacement],settings:{calendarBackground:'dunes'}});
assert.equal(restored.focusSessions[0].segments[0].end,at('09:45'),'Full backup keeps focus intervals');
assert.equal(Goal.goalMinutes(restored.items,'b',at('10:30')),30,'Restored focus contributes once');
assert.throws(()=>Goal.mergeBackup({items:[],settings:{}},{version:3,items:[],focusSessions:[{id:'bad',segments:'bad'}]}));
assert.equal(F.validate({...replacement,status:'running',segments:[]}),false,'An empty running session must not crash restoration');
assert.equal(F.validate({...replacement,segments:[{start:at('09:15'),end:at('09:45')},{start:at('09:30'),end:at('10:00')}]}),false,'A backup cannot double-credit overlapping segments in one session');
console.log('PASS overlap replacement without double credit and complete focus backup');
